-- Scheduled publication runs locally and in whichever isolated environment
-- eventually applies this migration. It does not touch production by itself.
create extension if not exists pg_cron with schema pg_catalog;
do $$
declare existing_job bigint;
begin
  select jobid into existing_job from cron.job where jobname='mcp930-devocional-publish-due' limit 1;
  if existing_job is not null then perform cron.unschedule(existing_job); end if;
  perform cron.schedule('mcp930-devocional-publish-due','* * * * *','select public.devocional_publish_due();');
end $$;
