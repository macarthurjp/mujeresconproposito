 perform set_config('app.devocional_guard_bypass','on',true);
 update public.devocionales set estado='borrador',publicado=false,fecha_publicacion=null,scheduled_at=null,published_at=null,pending_content=body,pending_fecha_publicacion=null,reviewer_id=null,review_started_at=null,updated_at=now() where id=p_id returning * into a;
 perform set_config('app.devocional_guard_bypass','off',true);
 insert into public.devocional_historial(devocional_id,devocional_titulo,devocional_slug,actor_id,actor_email,accion) values(p_id,a.titulo,a.slug,auth.uid(),auth.jwt()->>'email','devuelto_a_borrador');
 perform public.devocional_queue_email('devuelto_a_borrador',a,null);
end $$;

create or replace function public.devocional_soft_delete(p_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare a public.devocionales%rowtype;
begin
 select * into a from public.devocionales where id=p_id for update;
 if not found then raise exception 'Devocional no encontrado.'; end if;
 if a.estado='eliminado' then return; end if;
 if a.publicado or a.estado in ('programado','en_revision','pendiente_revision') then
   if not public.is_super_admin() then raise exception 'Solo Super Admin puede eliminar un devocional publicado o en flujo editorial.' using errcode='42501'; end if;
 elsif not public.is_super_admin() and (a.created_by is distinct from auth.uid() or not public.has_admin_module_permission('devotionals','delete')) then
   raise exception 'No tienes permiso para eliminar este borrador.' using errcode='42501';
 end if;
 perform set_config('app.devocional_guard_bypass','on',true);
 update public.devocionales set estado='eliminado',publicado=false,fecha_publicacion=null,scheduled_at=null,deleted_at=now(),reviewer_id=null,review_started_at=null,updated_at=now() where id=p_id returning * into a;
 perform set_config('app.devocional_guard_bypass','off',true);
 insert into public.devocional_historial(devocional_id,devocional_titulo,devocional_slug,actor_id,actor_email,accion) values(p_id,a.titulo,a.slug,auth.uid(),auth.jwt()->>'email','eliminado');
 perform public.devocional_queue_email('eliminado',a,null);
end $$;

create or replace function public.devocional_publish_due()
returns integer language plpgsql security definer set search_path = '' as $$
declare a public.devocionales%rowtype; n integer:=0;
begin
 for a in select * from public.devocionales where estado='programado' and scheduled_at<=now() and deleted_at is null for update skip locked loop
   perform set_config('app.devocional_guard_bypass','on',true);
   update public.devocionales set estado='publicado',publicado=true,fecha_publicacion=scheduled_at,published_at=now(),updated_at=now() where id=a.id returning * into a;
   perform set_config('app.devocional_guard_bypass','off',true);
   insert into public.devocional_historial(devocional_id,devocional_titulo,devocional_slug,accion,nota) values(a.id,a.titulo,a.slug,'publicado','Publicación automática por horario');
   perform public.devocional_queue_email('publicado',a,null);
   n:=n+1;
 end loop;
 return n;
end $$;

