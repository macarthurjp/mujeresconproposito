-- Editorial workflow v2. Additive migration: preserves the centralized
-- admin permission model and existing devotional records/authorship.

alter table public.devocionales
  add column if not exists reviewer_id uuid references auth.users(id) on delete set null,
  add column if not exists submitted_at timestamptz,
  add column if not exists review_started_at timestamptz,
  add column if not exists scheduled_at timestamptz,
  add column if not exists published_at timestamptz,
  add column if not exists deleted_at timestamptz,
  add column if not exists cover_alt text,
  add column if not exists serie text,
  add column if not exists etiquetas text[] not null default '{}',
  add column if not exists aplicacion_html text,
  add column if not exists oracion_html text;

alter table public.devocionales drop constraint if exists devocionales_estado_check;
alter table public.devocionales add constraint devocionales_estado_check
  check (estado in ('borrador','pendiente_revision','en_revision','cambios_solicitados','programado','publicado','eliminado'));

-- Old en_revision rows were waiting in the queue (there was no claim state).
update public.devocionales set estado='pendiente_revision'
where estado='en_revision' and reviewer_id is null and publicado=false;
update public.devocionales set estado='publicado', published_at=coalesce(published_at,fecha_publicacion,updated_at,now())
where publicado=true and deleted_at is null;

alter table public.devocional_historial drop constraint if exists devocional_historial_accion_check;
alter table public.devocional_historial add constraint devocional_historial_accion_check
  check (accion in ('creado','editado','guardado_automatico','enviado_a_revision','revision_tomada','revision_liberada','cambios_solicitados','retirado','aprobado_publicado','programado','publicado','despublicado','devuelto_a_borrador','eliminado'));

create index if not exists devocionales_review_queue_idx
  on public.devocionales (estado, submitted_at) where deleted_at is null;
create index if not exists devocionales_scheduled_idx
  on public.devocionales (scheduled_at) where estado='programado';

-- Transactional private email outbox. Autosaves never enqueue email.
create table if not exists public.devocional_email_outbox (
  id bigint generated by default as identity primary key,
  dedupe_key text not null unique,
  event_type text not null,
  devotional_id bigint,
  recipients text[] not null default '{}',
  payload jsonb not null default '{}',
  available_at timestamptz not null default now(),
  sent_at timestamptz,
  attempts integer not null default 0,
  last_error text,
  created_at timestamptz not null default now()
);
alter table public.devocional_email_outbox enable row level security;
revoke all on public.devocional_email_outbox from anon, authenticated;
grant all on public.devocional_email_outbox to service_role;

create or replace function public.devocional_queue_email(p_event text,p_article public.devocionales,p_note text default null)
returns void language plpgsql security definer set search_path = '' as $$
declare emails text[] := '{}'; recipients uuid[] := '{}'; title text;
begin
  title:=coalesce(p_article.pending_content->>'titulo',p_article.titulo,'Devocional');
  if p_event='enviado_a_revision' then
    select coalesce(array_agg(distinct u.email), '{}') into emails
    from public.user_roles r join auth.users u on u.id=r.user_id
    where not coalesce(r.is_revoked,false)
      and (
        coalesce(r.is_super_admin,false)
        or (
          not public.admin_user_is_view_only(r.user_id)
          and case
            when exists (
              select 1 from public.admin_user_permission_overrides o
              where o.user_id=r.user_id and o.permission_key='devotionals.publish'
            ) then (
              select o.allowed from public.admin_user_permission_overrides o
              where o.user_id=r.user_id and o.permission_key='devotionals.publish'
            )
            when exists (select 1 from public.admin_role_assignments a where a.user_id=r.user_id) then
              exists (
                select 1 from public.admin_role_assignments a
                join public.admin_role_permissions p on p.role_id=a.role_id
                where a.user_id=r.user_id and p.permission_key='devotionals.publish'
              )
            else 'reviewer'=any(coalesce(r.permissions,'{}'))
          end
        )
      )
      and u.email is not null and r.user_id<>p_article.created_by;
  else
    select coalesce(array_agg(u.email), '{}'), coalesce(array_agg(u.id), '{}')
      into emails,recipients from auth.users u
      where u.id=case when p_event in ('revision_tomada','revision_liberada') then p_article.created_by else p_article.created_by end
        and u.email is not null;
  end if;
  if cardinality(emails)=0 then return; end if;
  insert into public.devocional_email_outbox(dedupe_key,event_type,devotional_id,recipients,payload)
  values (p_event||':'||p_article.id||':'||coalesce(p_article.updated_at::text,clock_timestamp()::text),p_event,p_article.id,emails,
    jsonb_build_object('titulo',title,'slug',p_article.slug,'autora',coalesce(p_article.autora,''),'nota',coalesce(p_note,'')))
  on conflict (dedupe_key) do nothing;
end;
$$;
revoke all on function public.devocional_queue_email(text,public.devocionales,text) from public,anon,authenticated;

-- Direct browser writes can only change an author's pending copy while it is
-- an editable draft. Author identity and review metadata are immutable here.
create or replace function public.devocionales_guard_direct_writes()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  author_name text;
begin
  if current_setting('app.devocional_guard_bypass',true)='on' then return new; end if;
  if tg_op='INSERT' then
    if new.created_by is distinct from auth.uid()
       or new.titulo is not null or new.resumen is not null or new.contenido is not null
       or new.introduccion_html is not null or new.contenido_html is not null
       or new.aplicacion_html is not null or new.oracion_html is not null
       or new.versiculo is not null or new.categorias <> '{}'
       or new.imagen_url is not null or new.publicado=true
       or new.fecha_publicacion is not null or new.estado<>'borrador' then
      raise exception 'Crea el borrador editorial mediante pending_content.' using errcode='42501';
    end if;
    select nullif(btrim(r.nombre),'') into author_name
      from public.user_roles r where r.user_id=auth.uid() and not coalesce(r.is_revoked,false);
    new.autora:=coalesce(author_name, nullif(split_part(auth.jwt()->>'email','@',1),''), 'Equipo Mujeres con Propósito');
    return new;
  end if;
  if (to_jsonb(new) - array['pending_content','pending_fecha_publicacion','updated_at'])
       is distinct from (to_jsonb(old) - array['pending_content','pending_fecha_publicacion','updated_at']) then
    raise exception 'Usa las acciones del flujo editorial para modificar este devocional.' using errcode='42501';
  end if;
  if old.created_by<>auth.uid() or old.estado not in ('borrador','cambios_solicitados') or old.publicado then
    raise exception 'El artículo está bloqueado mientras se encuentra en revisión o publicado.' using errcode='42501';
  end if;
  if (new.pending_content is distinct from old.pending_content or new.pending_fecha_publicacion is distinct from old.pending_fecha_publicacion) and not (
    public.has_admin_module_permission('devotionals','create') or public.has_admin_module_permission('devotionals','edit')) then
    raise exception 'No tienes permiso para editar devocionales.' using errcode='42501';
  end if;
  return new;
end;
$$;

-- Keep author/editor visibility and central permission checks. The reviewer
-- queue is only readable by users who can both edit and publish.
drop policy if exists "roles read devocionales" on public.devocionales;
create policy "roles read devocionales" on public.devocionales for select to authenticated
using (
  public.is_super_admin()
  or (public.has_admin_module_permission('devotionals','view') and created_by=auth.uid())
  or publicado=true
  or (public.has_admin_module_permission('devotionals','view') and public.has_admin_module_permission('devotionals','edit') and public.has_admin_module_permission('devotionals','publish') and created_by<>auth.uid() and estado in ('pendiente_revision','en_revision'))
);
drop policy if exists "roles update devocionales" on public.devocionales;
create policy "roles update devocionales" on public.devocionales for update to authenticated
using (created_by=auth.uid() and public.has_admin_module_permission('devotionals','edit'))
with check (created_by=auth.uid() and public.has_admin_module_permission('devotionals','edit'));

create or replace function public.devocional_submit_for_review(p_id bigint)
returns void language plpgsql security definer set search_path = '' as $$
declare a public.devocionales%rowtype;
begin
 select * into a from public.devocionales where id=p_id for update;
 if not found then raise exception 'Devocional no encontrado.'; end if;
 if a.created_by<>auth.uid() or not (public.has_admin_module_permission('devotionals','create') or public.has_admin_module_permission('devotionals','edit')) then raise exception 'No tienes permiso para enviar este devocional a revisión.' using errcode='42501'; end if;
 if a.estado not in ('borrador','cambios_solicitados') or a.publicado then raise exception 'Este devocional no se puede enviar ahora.'; end if;
 if a.pending_content is null or coalesce(btrim(a.pending_content->>'titulo'),'')='' or coalesce(btrim(a.pending_content->>'contenido'),'')='' then raise exception 'Completa el título y la reflexión.'; end if;
 perform set_config('app.devocional_guard_bypass','on',true);
 update public.devocionales set estado='pendiente_revision',submitted_at=now(),reviewer_id=null,review_started_at=null,updated_at=now() where id=p_id returning * into a;
 perform set_config('app.devocional_guard_bypass','off',true);
 insert into public.devocional_historial(devocional_id,devocional_titulo,devocional_slug,actor_id,actor_email,accion) values(p_id,a.pending_content->>'titulo',a.slug,auth.uid(),auth.jwt()->>'email','enviado_a_revision');
 perform public.devocional_queue_email('enviado_a_revision',a,null);
end $$;

